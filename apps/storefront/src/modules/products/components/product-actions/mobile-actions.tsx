import { Dialog, Transition } from "@headlessui/react"
import { Button, clx } from "@modules/common/components/ui"
import React, { Fragment, useMemo } from "react"

import useToggleState from "@lib/hooks/use-toggle-state"
import ChevronDown from "@modules/common/icons/chevron-down"
import X from "@modules/common/icons/x"

import { getProductPrice } from "@lib/util/get-product-price"
import { compactSelectionLabel } from "@lib/util/print-format"
import { FORMAT_OPTION_TITLE, FINISH_OPTION_TITLE } from "@lib/util/product-options"
import OptionSelect from "./option-select"
import PrintOptions from "@modules/products/components/print-options"
import { HttpTypes } from "@medusajs/types"
import { isSimpleProduct } from "@lib/util/product"

type MobileActionsProps = {
  product: HttpTypes.StoreProduct
  variant?: HttpTypes.StoreProductVariant
  options: Record<string, string | undefined>
  updateOptions: (title: string, value: string) => void
  inStock?: boolean
  handleAddToCart: () => void
  isAdding?: boolean
  show: boolean
  optionsDisabled: boolean
  sortedOptions: HttpTypes.StoreProductOption[]
  formatValuesByPaper: Map<string, Set<string>>
  selectedPaper?: string
  allowedFinishes?: Set<string>
  showFinishPicker?: boolean
  printProduct?: boolean
  paperOption?: HttpTypes.StoreProductOption
  formatOption?: HttpTypes.StoreProductOption
  finishOption?: HttpTypes.StoreProductOption
}

const MobileActions: React.FC<MobileActionsProps> = ({
  product,
  variant,
  options,
  updateOptions,
  inStock,
  handleAddToCart,
  isAdding,
  show,
  optionsDisabled,
  sortedOptions,
  formatValuesByPaper,
  selectedPaper,
  allowedFinishes,
  showFinishPicker,
  printProduct,
  paperOption,
  formatOption,
  finishOption,
}) => {
  const { state, open, close } = useToggleState()

  const price = getProductPrice({
    product: product,
    variantId: variant?.id,
  })

  const selectedPrice = useMemo(() => {
    if (!price) {
      return null
    }
    const { variantPrice, cheapestPrice } = price

    return variantPrice || cheapestPrice || null
  }, [price])

  const isSimple = isSimpleProduct(product)

  return (
    <>
      <div
        className={clx("lg:hidden inset-x-0 bottom-0 fixed z-50", {
          "pointer-events-none": !show,
        })}
      >
        <Transition
          as={Fragment}
          show={show}
          enter="ease-in-out duration-300"
          enterFrom="opacity-0"
          enterTo="opacity-100"
          leave="ease-in duration-300"
          leaveFrom="opacity-100"
          leaveTo="opacity-0"
        >
          <div
            className="bg-paper flex flex-col gap-y-3 justify-center items-center text-large-regular p-4 h-full w-full border-t border-black/10"
            data-testid="mobile-actions"
          >
            <div className="flex items-center gap-x-2">
              <span data-testid="mobile-title">{product.title}</span>
              <span>—</span>
              {selectedPrice ? (
                <div className="flex items-end gap-x-2 text-ui-fg-base">
                  {selectedPrice.price_type === "sale" && (
                    <p>
                      <span className="line-through text-small-regular">
                        {selectedPrice.original_price}
                      </span>
                    </p>
                  )}
                  <span
                    className={clx({
                      "text-ui-fg-interactive":
                        selectedPrice.price_type === "sale",
                    })}
                  >
                    {selectedPrice.calculated_price}
                  </span>
                </div>
              ) : (
                <div></div>
              )}
            </div>
            <div className={clx("grid grid-cols-2 w-full gap-x-4", {
              "!grid-cols-1": isSimple
            })}>
              {!isSimple && <Button
                onClick={open}
                variant="secondary"
                className="w-full"
                data-testid="mobile-actions-button"
              >
                <div className="flex items-center justify-between w-full">
                  <span>
                    {variant
                      ? compactSelectionLabel(
                          options,
                          paperOption,
                          formatOption,
                          finishOption
                        ) || "Select size"
                      : "Select size"}
                  </span>
                  <ChevronDown />
                </div>
              </Button>}
              <Button
                onClick={handleAddToCart}
                disabled={!inStock || !variant}
                className="w-full"
                isLoading={isAdding}
                data-testid="mobile-cart-button"
              >
                {!variant
                  ? "Select variant"
                  : !inStock
                  ? "Out of stock"
                  : "Add to cart"}
              </Button>
            </div>
          </div>
        </Transition>
      </div>
      <Transition appear show={state} as={Fragment}>
        <Dialog as="div" className="relative z-[75]" onClose={close}>
          <Transition.Child
            as={Fragment}
            enter="ease-out duration-300"
            enterFrom="opacity-0"
            enterTo="opacity-100"
            leave="ease-in duration-200"
            leaveFrom="opacity-100"
            leaveTo="opacity-0"
          >
            <div className="fixed inset-0 bg-gray-700 bg-opacity-75 backdrop-blur-sm" />
          </Transition.Child>

          <div className="fixed bottom-0 inset-x-0">
            <div className="flex min-h-full h-full items-center justify-center text-center">
              <Transition.Child
                as={Fragment}
                enter="ease-out duration-300"
                enterFrom="opacity-0"
                enterTo="opacity-100"
                leave="ease-in duration-200"
                leaveFrom="opacity-100"
                leaveTo="opacity-0"
              >
                <Dialog.Panel
                  className="w-full h-full transform overflow-hidden text-left flex flex-col gap-y-3"
                  data-testid="mobile-actions-modal"
                >
                  <div className="w-full flex justify-end pr-6">
                    <button
                      onClick={close}
                      className="bg-white w-12 h-12 rounded-full text-ui-fg-base flex justify-center items-center"
                      data-testid="close-modal-button"
                    >
                      <X />
                    </button>
                  </div>
                  <div className="bg-surface px-6 py-10 max-h-[80vh] overflow-y-auto">
                    {(product.variants?.length ?? 0) > 1 &&
                      (printProduct ? (
                        <PrintOptions
                          product={product}
                          paperOption={paperOption}
                          formatOption={formatOption}
                          finishOption={finishOption}
                          options={options}
                          updateOption={updateOptions}
                          formatValuesByPaper={formatValuesByPaper}
                          allowedFinishes={allowedFinishes}
                          showFinishPicker={!!showFinishPicker}
                          disabled={optionsDisabled}
                        />
                      ) : (
                      <div className="flex flex-col gap-y-6">
                        {sortedOptions.map((option) => {
                          if (
                            option.title === FINISH_OPTION_TITLE &&
                            !showFinishPicker
                          ) {
                            return null
                          }

                          const allowedValues =
                            option.title === FORMAT_OPTION_TITLE &&
                            selectedPaper
                              ? formatValuesByPaper.get(selectedPaper)
                              : option.title === FINISH_OPTION_TITLE
                                ? allowedFinishes
                                : undefined

                          return (
                            <div key={option.id}>
                              <OptionSelect
                                option={option}
                                current={options[option.id]}
                                updateOption={updateOptions}
                                title={option.title ?? ""}
                                disabled={optionsDisabled}
                                allowedValues={allowedValues}
                              />
                            </div>
                          )
                        })}
                      </div>
                      ))}
                  </div>
                </Dialog.Panel>
              </Transition.Child>
            </div>
          </div>
        </Dialog>
      </Transition>
    </>
  )
}

export default MobileActions
